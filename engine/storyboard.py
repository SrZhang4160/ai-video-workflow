"""Editor step 1: storyboard.json → episode.js (drama v2).

  python3 engine/storyboard.py episodes/2026-11-04-sd

Writes episodes/<id>/episode.js = the storyboard + the episode's quiz embedded as data, followed by engine/drama2.js
(the scene builder). Then run engine/export.py and engine/render.py as usual.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ep = os.path.abspath(sys.argv[1])
    sb = json.load(open(os.path.join(ep, "storyboard.json")))
    quiz = json.load(open(os.path.join(ep, "meta.json"))).get("quiz", {})
    code = open(os.path.join(ROOT, "engine", "drama2.js")).read()
    out = (f"// generated by engine/storyboard.py from storyboard.json: edit the storyboard, not this file\n"
           f"window.STORYBOARD = {json.dumps(sb, ensure_ascii=False)};\nwindow.QUIZ = {json.dumps(quiz, ensure_ascii=False)};\n{code}")
    open(os.path.join(ep, "episode.js"), "w").write(out)
    live = sum(1 for s in sb["shots"] if s["gen"]["mode"] == "live")
    print(f"{os.path.basename(ep)}: episode.js from {len(sb['shots'])} shots ({live} live)")


if __name__ == "__main__":
    main()
